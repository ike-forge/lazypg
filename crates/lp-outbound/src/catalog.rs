//! Introspection: `pg_catalog` into our [`Catalog`]. One query per kind of
//! object, run together over the session's pipeline.

use lp_domain::model::{
    Catalog, Column, Constraint, ConstraintKind, DbError, ForeignKey, Function, FunctionKind,
    Index, PrimaryKey, RelationKind, RelationRef, Schema, Sequence, Server, Table,
};
use tokio_postgres::{Client, Row};

/// System schemas, toast and other sessions' temporary schemas.
macro_rules! user_schemas {
    ($alias:literal) => {
        concat!(
            $alias,
            ".nspname NOT IN ('pg_catalog', 'information_schema') AND ",
            $alias,
            ".nspname !~ '^pg_(toast|temp_)'"
        )
    };
}

/// Templates take no sessions; `datallowconn` and `CONNECT` are what a
/// switch would be refused on.
const SERVER: &str = "
    SELECT current_database()::text,
           ARRAY(SELECT datname::text FROM pg_database
                 WHERE datallowconn AND NOT datistemplate
                   AND has_database_privilege(datname, 'CONNECT')
                 ORDER BY 1)";

const SCHEMAS: &str = concat!(
    "SELECT n.nspname FROM pg_namespace n WHERE ",
    user_schemas!("n")
);

/// Partitions are folded under their parent, so never listed themselves.
const RELATIONS: &str = concat!(
    "SELECT n.nspname, c.relname, c.relkind::text,
            obj_description(c.oid, 'pg_class'),
            CASE WHEN c.relkind IN ('v', 'm') THEN pg_get_viewdef(c.oid) END
     FROM pg_class c
     JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE c.relkind IN ('r', 'p', 'v', 'm', 'f') AND NOT c.relispartition AND ",
    user_schemas!("n")
);

const COLUMNS: &str = concat!(
    "SELECT n.nspname, c.relname, a.attname,
            format_type(a.atttypid, a.atttypmod),
            NOT a.attnotnull,
            CASE
              WHEN a.attidentity = 'a' THEN 'generated always as identity'
              WHEN a.attidentity = 'd' THEN 'generated by default as identity'
              WHEN a.attgenerated = 's'
                THEN 'generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
              ELSE pg_get_expr(d.adbin, d.adrelid)
            END,
            col_description(c.oid, a.attnum)
     FROM pg_class c
     JOIN pg_namespace n ON n.oid = c.relnamespace
     JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
     LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
     WHERE c.relkind IN ('r', 'p', 'v', 'm', 'f') AND NOT c.relispartition AND ",
    user_schemas!("n"),
    " ORDER BY 1, 2, a.attnum"
);

/// Key columns by `conkey` position, which is key order.
const CONSTRAINTS: &str = concat!(
    "SELECT n.nspname, c.relname, con.conname, con.contype::text,
            pg_get_constraintdef(con.oid),
            ARRAY(SELECT a.attname::text
                  FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord)
                  JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum
                  ORDER BY k.ord),
            fn.nspname::text, fc.relname::text,
            ARRAY(SELECT a.attname::text
                  FROM unnest(con.confkey) WITH ORDINALITY k(attnum, ord)
                  JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum
                  ORDER BY k.ord),
            con.confupdtype::text, con.confdeltype::text
     FROM pg_constraint con
     JOIN pg_class c ON c.oid = con.conrelid
     JOIN pg_namespace n ON n.oid = c.relnamespace
     LEFT JOIN pg_class fc ON fc.oid = con.confrelid
     LEFT JOIN pg_namespace fn ON fn.oid = fc.relnamespace
     WHERE con.contype IN ('p', 'f', 'c', 'u', 'x') AND NOT c.relispartition AND ",
    user_schemas!("n"),
    " ORDER BY 1, 2, 3"
);

/// A key is a column name or the expression's text, as `pg_get_indexdef`
/// renders one position.
const INDEXES: &str = concat!(
    "SELECT n.nspname, c.relname, i.relname,
            pg_get_indexdef(x.indexrelid),
            ARRAY(SELECT pg_get_indexdef(x.indexrelid, k, true)
                  FROM generate_series(1, x.indnkeyatts) k ORDER BY k),
            x.indisunique, x.indisprimary, am.amname::text,
            pg_get_expr(x.indpred, x.indrelid, true)
     FROM pg_index x
     JOIN pg_class i ON i.oid = x.indexrelid
     JOIN pg_class c ON c.oid = x.indrelid
     JOIN pg_namespace n ON n.oid = c.relnamespace
     JOIN pg_am am ON am.oid = i.relam
     WHERE NOT c.relispartition AND ",
    user_schemas!("n"),
    " ORDER BY 1, 2, 3"
);

const PARTITIONS: &str = concat!(
    "SELECT n.nspname, p.relname, c.relname
     FROM pg_inherits h
     JOIN pg_class c ON c.oid = h.inhrelid
     JOIN pg_class p ON p.oid = h.inhparent
     JOIN pg_namespace n ON n.oid = p.relnamespace
     WHERE c.relispartition AND ",
    user_schemas!("n"),
    " ORDER BY 1, 2, 3"
);

/// The owner is the column a serial or identity column's sequence belongs to.
const SEQUENCES: &str = concat!(
    "SELECT n.nspname, c.relname, format_type(s.seqtypid, NULL),
            (SELECT oc.relname || '.' || a.attname
             FROM pg_depend d
             JOIN pg_class oc ON oc.oid = d.refobjid
             JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid
             WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid
               AND d.refclassid = 'pg_class'::regclass AND d.deptype IN ('a', 'i')
             LIMIT 1)
     FROM pg_sequence s
     JOIN pg_class c ON c.oid = s.seqrelid
     JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE ",
    user_schemas!("n"),
    " ORDER BY 1, 2"
);

/// An extension's functions are the extension's, not the schema's author's.
const FUNCTIONS: &str = concat!(
    "SELECT n.nspname, p.proname, p.prokind::text,
            pg_get_function_identity_arguments(p.oid),
            CASE WHEN p.prokind = 'p' THEN '' ELSE pg_get_function_result(p.oid) END
     FROM pg_proc p
     JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE NOT EXISTS (SELECT 1 FROM pg_depend d
                       WHERE d.classid = 'pg_proc'::regclass AND d.objid = p.oid
                         AND d.deptype = 'e')
       AND ",
    user_schemas!("n"),
    " ORDER BY 1, 2, 4"
);

pub(crate) async fn describe(client: &Client) -> Result<Catalog, DbError> {
    let query = |sql: &'static str| async move {
        client
            .query(sql, &[])
            .await
            .map_err(|error| crate::postgres::db_error(&error))
    };
    let (
        server,
        schemas,
        relations,
        columns,
        constraints,
        indexes,
        partitions,
        sequences,
        functions,
    ) = tokio::try_join!(
        query(SERVER),
        query(SCHEMAS),
        query(RELATIONS),
        query(COLUMNS),
        query(CONSTRAINTS),
        query(INDEXES),
        query(PARTITIONS),
        query(SEQUENCES),
        query(FUNCTIONS),
    )?;

    let mut catalog = Catalog {
        server: server.first().map(server_of),
        schemas: schemas
            .iter()
            .map(|row| {
                let name: String = row.get(0);
                (name.clone(), Schema::empty(&name))
            })
            .collect(),
    };

    for row in &relations {
        let Some(schema) = catalog.schemas.get_mut(&row.get::<_, String>(0)) else {
            continue;
        };
        let name: String = row.get(1);
        let table = Table {
            name: name.clone(),
            kind: relation_kind(&row.get::<_, String>(2)),
            comment: row.get(3),
            definition: row.get(4),
            ..Table::default()
        };
        schema.tables.insert(name, table);
    }

    let mut tables = Tables(&mut catalog);

    for row in &columns {
        if let Some(table) = tables.at(row) {
            table.columns.push(Column {
                name: row.get(2),
                data_type: row.get(3),
                nullable: row.get(4),
                default: row.get(5),
                comment: row.get(6),
            });
        }
    }

    for row in &constraints {
        if let Some(table) = tables.at(row) {
            constraint(table, row);
        }
    }

    for row in &indexes {
        if let Some(table) = tables.at(row) {
            table.indexes.push(Index {
                name: row.get(2),
                definition: row.get(3),
                keys: row.get(4),
                unique: row.get(5),
                primary: row.get(6),
                method: row.get(7),
                predicate: row.get(8),
            });
        }
    }

    for row in &partitions {
        if let Some(table) = tables.at(row) {
            table.partitions.push(row.get(2));
        }
    }

    schema_objects(&mut catalog, &sequences, &functions);

    Ok(catalog)
}

fn server_of(row: &Row) -> Server {
    let current: String = row.get(0);
    let mut databases: Vec<String> = row.get(1);
    // Connected, so allowed, whatever the privilege check said.
    if !databases.contains(&current) {
        databases.push(current.clone());
        databases.sort();
    }
    Server { current, databases }
}

fn schema_objects(catalog: &mut Catalog, sequences: &[Row], functions: &[Row]) {
    for row in sequences {
        if let Some(schema) = catalog.schemas.get_mut(&row.get::<_, String>(0)) {
            schema.sequences.push(Sequence {
                name: row.get(1),
                data_type: row.get(2),
                owned_by: row.get(3),
            });
        }
    }

    for row in functions {
        if let Some(schema) = catalog.schemas.get_mut(&row.get::<_, String>(0)) {
            schema.functions.push(Function {
                name: row.get(1),
                kind: function_kind(&row.get::<_, String>(2)),
                arguments: row.get(3),
                result: row.get::<_, Option<String>>(4).unwrap_or_default(),
            });
        }
    }
}

/// Rows lead with schema and relation name; a row for a relation not listed
/// (a race with DDL between queries) is skipped.
struct Tables<'a>(&'a mut Catalog);

impl Tables<'_> {
    fn at(&mut self, row: &Row) -> Option<&mut Table> {
        self.0
            .schemas
            .get_mut(&row.get::<_, String>(0))?
            .tables
            .get_mut(&row.get::<_, String>(1))
    }
}

fn constraint(table: &mut Table, row: &Row) {
    let name: String = row.get(2);
    let definition: String = row.get(4);
    let columns: Vec<String> = row.get(5);

    let kind = match row.get::<_, String>(3).as_str() {
        "p" => {
            table.primary_key = Some(PrimaryKey { name, columns });
            return;
        }
        "f" => {
            let target = row
                .get::<_, Option<String>>(6)
                .zip(row.get::<_, Option<String>>(7))
                .map(|(schema, table)| RelationRef { schema, table });
            if let Some(target) = target {
                table.foreign_keys.push(ForeignKey {
                    name,
                    columns,
                    target,
                    target_columns: row.get(8),
                    on_update: action(&row.get::<_, String>(9)).to_owned(),
                    on_delete: action(&row.get::<_, String>(10)).to_owned(),
                });
            }
            return;
        }
        "u" => ConstraintKind::Unique,
        "x" => ConstraintKind::Exclusion,
        _ => ConstraintKind::Check,
    };

    table.constraints.push(Constraint {
        name,
        kind,
        definition,
    });
}

fn relation_kind(code: &str) -> RelationKind {
    match code {
        "p" => RelationKind::Partitioned,
        "v" => RelationKind::View,
        "m" => RelationKind::MaterializedView,
        "f" => RelationKind::Foreign,
        _ => RelationKind::Table,
    }
}

fn function_kind(code: &str) -> FunctionKind {
    match code {
        "p" => FunctionKind::Procedure,
        "a" => FunctionKind::Aggregate,
        "w" => FunctionKind::Window,
        _ => FunctionKind::Function,
    }
}

/// `pg_constraint.confupdtype` and `confdeltype`.
fn action(code: &str) -> &'static str {
    match code {
        "r" => "RESTRICT",
        "c" => "CASCADE",
        "n" => "SET NULL",
        "d" => "SET DEFAULT",
        _ => "NO ACTION",
    }
}
